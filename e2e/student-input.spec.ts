import { test, expect, fillTemplate } from './fixtures';
import { solutions } from '../tests/fixtures/casePrograms';

test('key rack, revised notes and direct archive flow work with the keypad and audible wheels', async ({ page }, testInfo) => {
  await page.addInitScript(() => {
    const tracked = window as Window & { terminalClicks: number };
    tracked.terminalClicks = 0;
    if (typeof AudioBufferSourceNode === 'undefined') return;
    const start = AudioBufferSourceNode.prototype.start;
    AudioBufferSourceNode.prototype.start = function (when) {
      tracked.terminalClicks++;
      start.call(this, when);
    };
  });
  await page.goto('/case/001');
  await page.locator('.step-tab').nth(1).click();
  await fillTemplate(page, solutions[1]);
  await page.getByRole('button', { name: 'RUN CASE', exact: true }).click();
  await page.getByRole('dialog', { name: 'New evidence recovered' }).getByRole('button', { name: /Missing key record/ }).click();
  const record = page.getByRole('dialog', { name: 'Missing key record', exact: true });
  const rack = record.getByRole('img', { name: 'Maker Lab key rack', exact: true });
  await expect(rack.locator('.key-position')).toHaveCount(30);
  await expect(rack.locator('.rack-key')).toHaveCount(29);
  const labels = await rack.locator('.key-number').allTextContents();
  expect(labels).toEqual(Array.from({ length: 30 }, (_, index) => String(index + 1).padStart(2, '0')).filter(value => value !== '27'));
  await expect(record).not.toContainText(/MISSING KEY: 27|K27|MISSING KEY 27/);
  await expect(record.locator('img')).toHaveCount(0);
  await record.screenshot({ path: `test-results/${testInfo.project.name}-key-rack.png` });
  await record.getByRole('button', { name: 'Close dialog' }).click();

  await page.locator('.step-tab').nth(0).click();
  await fillTemplate(page, solutions[0]);
  await page.getByRole('button', { name: 'RUN CASE', exact: true }).click();
  await page.getByRole('dialog', { name: 'New evidence recovered' }).getByRole('button', { name: 'Close dialog' }).click();
  await page.locator('.step-tab').nth(2).click();
  const notes = page.locator('.guided-notes');
  await expect(notes).toContainText('The inspector said that Brian left the room 20 minutes before 16:00.');
  await expect(notes).not.toContainText(/hour 15|minute was 40/);
  await fillTemplate(page, solutions[2]);
  await page.getByRole('button', { name: 'RUN CASE', exact: true }).click();
  const terminal = page.getByRole('dialog', { name: 'CCTV archive terminal' });
  await expect(terminal).toBeVisible();
  await expect(page.getByRole('dialog', { name: 'New evidence recovered' })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Open Last seen record', exact: true })).toHaveCount(0);

  const keypad = terminal.getByRole('group', { name: 'Camera code keypad' });
  await expect(keypad.getByRole('button')).toHaveCount(12);
  await keypad.getByRole('button', { name: '1', exact: true }).click();
  await keypad.getByRole('button', { name: '7', exact: true }).click();
  await keypad.getByRole('button', { name: 'Delete last digit', exact: true }).click();
  await expect(terminal.getByLabel('ENTER CAMERA CODE')).toHaveValue('1');
  await keypad.getByRole('button', { name: 'Clear camera code', exact: true }).click();
  await expect(terminal.getByLabel('ENTER CAMERA CODE')).toHaveValue('');
  for (const digit of ['2', '8', '0']) await keypad.getByRole('button', { name: digit, exact: true }).click();
  await expect(terminal.getByLabel('ENTER CAMERA CODE')).toHaveValue('280');
  for (const button of await keypad.getByRole('button').all()) expect((await button.boundingBox())!.height).toBeGreaterThanOrEqual(44);
  await terminal.screenshot({ path: `test-results/${testInfo.project.name}-camera-keypad.png` });
  await terminal.getByRole('button', { name: /VERIFY CAMERA/ }).click();
  await terminal.getByRole('button', { name: /SEARCH ARCHIVE/ }).click();
  await expect(terminal.getByRole('status')).toContainText('CHECK YOUR STEP 03 RESULT');
  const hour = terminal.getByRole('spinbutton', { name: 'hour', exact: true });
  await hour.focus();
  await page.keyboard.press('PageDown'); await page.keyboard.press('PageDown'); await page.keyboard.press('ArrowUp');
  for (let i = 0; i < 4; i++) await terminal.getByRole('button', { name: 'Back 5 minutes', exact: true }).click();
  await expect(hour).toHaveAttribute('aria-valuenow', '15');
  await expect(terminal.getByRole('spinbutton', { name: 'minute', exact: true })).toHaveAttribute('aria-valuenow', '40');
  const audioAvailable = await page.evaluate(() => Boolean(window.AudioContext || (window as Window & { webkitAudioContext?: typeof AudioContext }).webkitAudioContext));
  expect(await page.evaluate(() => (window as Window & { terminalClicks: number }).terminalClicks)).toBe(audioAvailable ? 14 : 0);
  await terminal.getByRole('button', { name: /SEARCH ARCHIVE/ }).click();
  await expect(terminal).toContainText('ARCHIVE FOUND');
  await terminal.getByRole('button', { name: /CONTINUE TO THE FOOTAGE/ }).click();
  await expect(notes).toContainText('The color filter value is in your evidence.');
  await expect(notes).not.toContainText('The color filter value is 2.');
  await page.getByRole('button', { name: 'Open Original CCTV frame', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('COLOR FILTER N# 2');
  await expect(page.getByRole('dialog')).not.toContainText('use color_filter = 2 to restore Archive 1220.');
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await fillTemplate(page, solutions[3]);
  await page.getByRole('button', { name: 'RUN CASE', exact: true }).click();
  await page.getByRole('dialog', { name: 'New evidence recovered' }).getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'NEXT STEP', exact: true }).click();
  await expect(notes).toContainText('The correction value is the number used as midday.');
  await expect(notes).not.toContainText('The correction value is 12.');
});
